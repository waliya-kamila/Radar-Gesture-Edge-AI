"""Convert one INT8 .tflite TinyRadarCNN + its input normalisation into a C header.

usage: python export_model.py model_int8.tflite norm.json SUBJECT out/model_data.h
"""
import sys, json
import numpy as np
try:
    from ai_edge_litert.interpreter import Interpreter
except ImportError:
    import tensorflow as tf
    Interpreter = tf.lite.Interpreter

tfl, norm_path, subj, out = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
it = Interpreter(model_path=tfl)
it.allocate_tensors()
T = {t['index']: t for t in it.get_tensor_details()}
q = lambda i: (T[i]['quantization_parameters']['scales'].astype(np.float64),
               T[i]['quantization_parameters']['zero_points'].astype(int))
ops = [op for op in it._get_ops_details() if op['op_name'] != 'DELEGATE']
assert [o['op_name'] for o in ops] == ['CONV_2D', 'MAX_POOL_2D', 'CONV_2D', 'MAX_POOL_2D',
                                       'CONV_2D', 'MEAN', 'FULLY_CONNECTED'], [o['op_name'] for o in ops]
norm = json.load(open(norm_path))[str(subj)]
inp = it.get_input_details()[0]

def arr(name, ctype, values, per_line=16):
    v = list(values)
    body = ',\n  '.join(', '.join(str(x) for x in v[i:i + per_line]) for i in range(0, len(v), per_line))
    return f"static const {ctype} {name}[{len(v)}] = {{\n  {body}\n}};\n"

fl = lambda x: f"{float(x):.9e}f"
lines = ["/* Auto-generated by tools/export_model.py: do not edit. */",
         f"/* Source: {tfl.split('/')[-1]}  (LOSO model that never saw participant {subj}) */",
         "#ifndef MODEL_DATA_H", "#define MODEL_DATA_H", "#include <stdint.h>", "",
         f"#define IN_SCALE {fl(inp['quantization'][0])}", f"#define IN_ZP {int(inp['quantization'][1])}",
         arr('NORM_MEAN', 'float', [fl(m) for m in norm['mean']]),
         arr('NORM_STD', 'float', [fl(s) for s in norm['std']])]
conv_i = 0
for op in ops:
    ins = [i for i in op['inputs'] if i >= 0]
    (si, zi), (so, zo) = q(ins[0]), q(op['outputs'][0])
    if op['op_name'] == 'CONV_2D':
        conv_i += 1
        w = it.get_tensor(ins[1]); ws = q(ins[1])[0]
        p = f"C{conv_i}"
        lines += [f"/* conv{conv_i}: {w.shape[3]} -> {w.shape[0]} channels, 3x3, weights [O][ky][kx][C] */",
                  f"#define {p}_IN {w.shape[3]}", f"#define {p}_OUT {w.shape[0]}",
                  f"#define {p}_IN_ZP {int(zi[0])}", f"#define {p}_OUT_ZP {int(zo[0])}",
                  arr(f"{p}_W", 'int8_t', w.astype(np.int8).ravel()),
                  arr(f"{p}_B", 'int32_t', it.get_tensor(ins[2]).astype(np.int64).ravel()),
                  arr(f"{p}_M", 'float', [fl(si[0] * s / so[0]) for s in ws])]
    elif op['op_name'] == 'MEAN':
        lines += ["/* global average pool */", f"#define GAP_IN_ZP {int(zi[0])}", f"#define GAP_OUT_ZP {int(zo[0])}",
                  f"#define GAP_M {fl(si[0] / so[0])}"]
    elif op['op_name'] == 'FULLY_CONNECTED':
        w = it.get_tensor(ins[1]); ws = q(ins[1])[0]
        lines += ["/* classifier */", f"#define FC_IN {w.shape[1]}", f"#define FC_OUT {w.shape[0]}",
                  f"#define FC_IN_ZP {int(zi[0])}", f"#define FC_OUT_ZP {int(zo[0])}",
                  f"#define FC_OUT_SCALE {fl(so[0])}",
                  arr("FC_W", 'int8_t', w.astype(np.int8).ravel()),
                  arr("FC_B", 'int32_t', it.get_tensor(ins[2]).astype(np.int64).ravel()),
                  arr("FC_M", 'float', [fl(si[0] * s / so[0]) for s in ws])]
lines += ["#endif", ""]
open(out, 'w').write('\n'.join(lines))
print("wrote", out)
